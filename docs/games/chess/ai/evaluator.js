/** قيمة موضع قطعة بالنسبة للأبيض */
function pstValue(type, row, col, color) {
    const table = PST[type];
    if (!table) return 0;
    // الأسود يرى الرقعة معكوسة
    const idx = color === COLOR.WHITE
        ? row * 8 + col
        : (7 - row) * 8 + col;
    return table[idx] ?? 0;
}

// ─── الدالة الرئيسية ──────────────────────────────────────────────────────────

/**
 * تقييم موقف الرقعة
 * @param {import('../core/board.js').Board} board
 * @returns {number} موجب = أبيض أحسن، سالب = أسود أحسن
 */
export function evaluate(board) {
    let score = 0;

    for (let r = 0; r < 8; r++) {
        for (let c = 0; c < 8; c++) {
            const p = board.get(r, c);
            if (!p) continue;

            const material = PIECE_VALUE[p.type] ?? 0;
            const position = pstValue(p.type, r, c, p.color);
            const value    = material + position;

            score += p.color === COLOR.WHITE ? value : -value;
        }
    }

    return score;
}

/** قيمة القطعة فقط (بدون موضع) — للـ MVV-LVA */
export function pieceValue(type) {
    return PIECE_VALUE[type] ?? 0;
}
